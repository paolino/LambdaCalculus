app :: MonadWidget t m => m ()
app = void $ do
    header

    rec buttons <- buttonsW buttonsDef

        exampleClicked <- examplesW

        (expression, substitute)  <- expressionW  buttons upEC exampleClicked

        -- Dynamic has a real Functor/Applicative instance now, so this is
        -- plain zipDynWith instead of the old app's monadic combineDynWith
        -- shim (which existed because Dynamic didn't have one yet).
        let bf = zipDynWith toMaybe substitute buttonsDef
            f  = zipDynWith ReductionInput redType bf
            bdefsAndExpr = zipDynWith ($) f expression

        reductionE <- mapMorph dyn reductionW bdefsAndExpr

        let     newButton = pick NewButton reductionE
                upEC = pick NewEdit reductionE

        redType <- holdDyn Normal $ pick ChangeTactic reductionE

        buttonsDef <- foldDyn (flip (++) . return) boot newButton

    footer

start :: JSM ()
start = mainWidgetWithCss (T.encodeUtf8 css) app
